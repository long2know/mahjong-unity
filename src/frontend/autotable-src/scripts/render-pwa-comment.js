#!/usr/bin/env node
/* eslint-disable */
// Phase K Wave 10 — Render a Markdown summary of the Lighthouse 13 +
// manifest-lint PWA audit for posting as a PR comment.
//
// Reads:
//   --report      path to .lighthouse-report.report.json
//   --pwa-score   path to .pwa-score.json (manifest-lint output)
// Writes the rendered comment to stdout.
//
// Owned by Hicks.  Invoked by `.github/workflows/pwa-audit.yml`.

const fs = require('node:fs');

function parseArgs(argv) {
  const out = { report: null, pwaScore: null };
  for (let i = 0; i < argv.length; i += 1) {
    const k = argv[i];
    const v = argv[i + 1];
    if (k === '--report') { out.report = v; i += 1; }
    else if (k === '--pwa-score') { out.pwaScore = v; i += 1; }
  }
  return out;
}

function emoji(score) {
  if (score >= 0.9) return '🟢';
  if (score >= 0.7) return '🟡';
  return '🔴';
}

function formatCategory(name, score) {
  if (typeof score !== 'number') return `| ${name} | n/a |`;
  const pct = Math.round(score * 100);
  return `| ${name} | ${emoji(score)} ${pct} |`;
}

function bulletList(items) {
  if (!items || items.length === 0) return '_(none)_';
  return items.map(i => `\`${i}\``).join(', ');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  let report = {};
  let pwa = {};
  try { report = JSON.parse(fs.readFileSync(args.report, 'utf8')); } catch (e) { /* report missing */ }
  try { pwa = JSON.parse(fs.readFileSync(args.pwaScore, 'utf8')); } catch (e) { /* pwa missing */ }

  const cats = report.categories || {};
  const lh = name => cats[name] && typeof cats[name].score === 'number' ? cats[name].score : null;

  const pwaPct = Math.round((pwa.pwaScore || 0) * 100);
  const lines = [];
  lines.push(`## PWA audit — Lighthouse 13 + manifest-lint`);
  lines.push('');
  lines.push(`**Computed PWA score: ${emoji(pwa.pwaScore || 0)} ${pwaPct}** (gate: ≥ 90)`);
  lines.push('');
  lines.push('### Lighthouse 13 categories');
  lines.push('');
  lines.push('| Category | Score |');
  lines.push('|---|---|');
  lines.push(formatCategory('Performance', lh('performance')));
  lines.push(formatCategory('Accessibility', lh('accessibility')));
  lines.push(formatCategory('Best practices', lh('best-practices')));
  lines.push(formatCategory('SEO', lh('seo')));
  lines.push(formatCategory('Agentic browsing', lh('agentic-browsing')));
  lines.push('');
  lines.push('### Manifest installability');
  lines.push('');
  if (pwa.manifest) {
    lines.push(`- Required fields present: ${bulletList(pwa.manifest.present)}`);
    if (pwa.manifest.missing && pwa.manifest.missing.length > 0) {
      lines.push(`- ❌ Missing: ${bulletList(pwa.manifest.missing)}`);
    } else {
      lines.push('- ✅ No required fields missing.');
    }
    if (pwa.manifest.recommendedPresent && pwa.manifest.recommendedPresent.length > 0) {
      lines.push(`- Recommended fields present: ${bulletList(pwa.manifest.recommendedPresent)}`);
    }
  }
  if (pwa.icons) {
    if (pwa.icons.ok) {
      lines.push(`- ✅ Icons: ${pwa.icons.sizes.length} sizes (${bulletList(pwa.icons.sizes)})`);
    } else {
      lines.push(`- ❌ Icons missing: ${bulletList(pwa.icons.missing)}`);
    }
  }
  if (pwa.screenshots) {
    if (pwa.screenshots.ok) {
      lines.push(`- ✅ Screenshots: ${pwa.screenshots.count} (${bulletList(pwa.screenshots.formFactors)})`);
    } else {
      lines.push(`- ⚠️ Screenshots: ${pwa.screenshots.count} — need ≥ 2 with both \`wide\` and \`narrow\` form factors.`);
    }
  }
  if (pwa.shortcuts) {
    if (pwa.shortcuts.ok) {
      lines.push(`- ✅ Shortcuts: ${pwa.shortcuts.count}`);
    } else {
      lines.push('- ⚠️ Shortcuts: none declared.');
    }
  }
  lines.push('');
  lines.push('_Generated by [`pwa-audit`](.github/workflows/pwa-audit.yml) — see `docs/frontend-pwa-audit.md §4` for the gate definition._');
  process.stdout.write(lines.join('\n') + '\n');
}

main();
